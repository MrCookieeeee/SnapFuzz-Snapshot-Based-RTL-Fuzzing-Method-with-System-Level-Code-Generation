def cal_instr_per(instr_prob: dict = None):
    # 总和
    active_instr_prob = (
        ISAInstClass_Initial_Boosters if instr_prob is None else instr_prob
    )
    total_weight = sum(active_instr_prob.values())

    # 计算百分比
    result = {}
    for group, members in Instr_Groups.items():
        # instr_type  -> alu, mul.....
        # instr_class -> ISAInstrClass.DESCEND_PRV.....
        group_weight = 0
        for instr_type in members:
            instr_class   = Instr_Mapping[instr_type]
            # print(f"{instr_type}: {active_instr_prob[instr_class]}")
            group_weight += active_instr_prob[instr_class]
        result[group] = round((group_weight / total_weight) * 100, 4)  # 保留四位小数 %

    return result

# FPU classes that receive the fpuweight discount (E[fpuweight]=0.5)
_FPU_DISCOUNTED_CLASSES = {
    ISAInstrClass.MEMFPU, ISAInstrClass.FPU, ISAInstrClass.FPU64,
    ISAInstrClass.MEMFPUD, ISAInstrClass.FPUD, ISAInstrClass.FPUD64,
}

def cal_effective_instr_per(instr_prob: dict = None):
    """Compute expected percentages accounting for E[fpuweight]=0.5 on FPU classes.

    This gives a more realistic 'expected' distribution that matches what
    gen_pick_weights() produces on average, before dynamic filtering.
    """
    active_instr_prob = (
        ISAInstClass_Initial_Boosters if instr_prob is None else instr_prob
    )
    effective_weights = {}
    for cls, w in active_instr_prob.items():
        if cls in _FPU_DISCOUNTED_CLASSES:
            effective_weights[cls] = w * 0.5  # E[random.random()] = 0.5
        else:
            effective_weights[cls] = w

    total = sum(effective_weights.values())
    result = {}
    for group, members in Instr_Groups.items():
        group_weight = sum(effective_weights[Instr_Mapping[m]] for m in members)
        result[group] = round((group_weight / total) * 100, 4)
    return result

def get_range_bits_per_instrclass(isaclass: ISAInstrClass):
    if isaclass == ISAInstrClass.BRANCH:
        return 12
    elif isaclass == ISAInstrClass.JAL:
        return 20
    elif isaclass == ISAInstrClass.JALR:
        return 31
    elif isaclass in (ISAInstrClass.EXCEPTION, ISAInstrClass.DESCEND_PRV):
        return 31 # xtvec and xepc can send to everywhere
    else:
        print('isaclass:', isaclass)
        raise ValueError(f"Unsupported control flow ISA class: {isaclass}")

def _gen_next_isainstrclass_from_weights(weights: list = None) -> ISAInstrClass:
    """
    Args:
        weights a list either None (equal weights) or as long as ISAInstrClass

    Return:
        ISAInstrClass
    """
    ret = None
    instr_classes = list(ISAInstrClass)
    instr_weights = [weights[c] for c in instr_classes]
    ret = random.choices(instr_classes, weights=instr_weights)[0]
    return ret

# Do NOT @cache this function, as it is a random function.
def gen_next_isainstrclass(fuzzerstate) -> ISAInstrClass:
    # 更新了每个参数被选择的概率，关闭了一些类别的指令
    filtered_weights = _get_isainstrclass_filtered_weights(fuzzerstate)
    _filter_regfsm_weight(fuzzerstate, filtered_weights)
    _filter_sensitive_instr_weights(fuzzerstate, filtered_weights)

    return _gen_next_isainstrclass_from_weights(filtered_weights)



def _get_isainstrclass_filtered_weights(fuzzerstate: 'FuzzerState'):
    """
    Filters the isainstrclass weights according to the capabilities of a given CPU
        
    TODO: 
        Use a Markov chain for executing floating point instructions in a row. 
    
    Returns:
        normalized dict of instruction classes supported by the CPU`
    """
    if DO_ASSERT:
        assert fuzzerstate.design_has_fpu or not fuzzerstate.design_has_fpud, "Cannot have double but not simple precision"
    ret_dict = copy.copy(fuzzerstate.isapickweights)
    if not fuzzerstate.is_design_64bit:
        ret_dict[ISAInstrClass.ALU64]    = 0
        ret_dict[ISAInstrClass.MULDIV64] = 0
        ret_dict[ISAInstrClass.AMO64]    = 0
        ret_dict[ISAInstrClass.MEM64]    = 0
        ret_dict[ISAInstrClass.FPU64]    = 0
        ret_dict[ISAInstrClass.FPUD64]   = 0
    if not fuzzerstate.design_has_fpu:
        ret_dict[ISAInstrClass.MEMFPU]   = 0
        ret_dict[ISAInstrClass.FPU]      = 0
        ret_dict[ISAInstrClass.FPU64]    = 0
        ret_dict[ISAInstrClass.MEMFPUD]  = 0
        ret_dict[ISAInstrClass.FPUD]     = 0
        ret_dict[ISAInstrClass.FPUD64]   = 0
        ret_dict[ISAInstrClass.FPUFSM]   = 0
    elif not fuzzerstate.is_fpu_activated:
        ret_dict[ISAInstrClass.MEMFPU]   = 0
        ret_dict[ISAInstrClass.FPU]      = 0
        ret_dict[ISAInstrClass.FPU64]    = 0
        ret_dict[ISAInstrClass.MEMFPUD]  = 0
        ret_dict[ISAInstrClass.FPUD]     = 0
        ret_dict[ISAInstrClass.FPUD64]   = 0
    if not fuzzerstate.design_has_fpud:
        ret_dict[ISAInstrClass.MEMFPUD] = 0
        ret_dict[ISAInstrClass.FPUD]    = 0
        ret_dict[ISAInstrClass.FPUD64]  = 0
    if not fuzzerstate.design_has_muldiv:
        ret_dict[ISAInstrClass.MULDIV]   = 0
        ret_dict[ISAInstrClass.MULDIV64] = 0
    if not fuzzerstate.design_has_amo:
        ret_dict[ISAInstrClass.AMO]   = 0
        ret_dict[ISAInstrClass.AMO64] = 0
    if not fuzzerstate.privilegestate.privstate == PrivilegeStateEnum.MACHINE:
        ret_dict[ISAInstrClass.FPUFSM] = 0
    
    if (not fuzzerstate.authorize_privileges) or not (fuzzerstate.privilegestate.privstate == PrivilegeStateEnum.MACHINE and fuzzerstate.design_has_supervisor_mode):
        # There is no notion of delegation if supervisor mode is not supported
        ret_dict[ISAInstrClass.MEDELEG] = 0
    


    # --------------------------------------------------------------------------------------
    # mtvec/stvec and mepc/sepc will populated manually 
    # only when we generate an execption
    # --------------------------------------------------------------------------------------
    # Do not descend privileges as long as medeleg is undefined because we have no way of certainly coming back up
    # However, this ISA class still encompasses setting mpp and spp bits, to we tolerate this ISA class at all times when executing as a non-user.
    # TODO
    if not is_ready_to_descend_privileges(fuzzerstate):
        ret_dict[ISAInstrClass.DESCEND_PRV] = 0
    
    # Decrease the proba if we know it will be a mpp/spp
    if (not fuzzerstate.authorize_privileges) or fuzzerstate.privilegestate.privstate != PrivilegeStateEnum.MACHINE: # To support sret from machine mode: `not in (PrivilegeStateEnum.MACHINE, PrivilegeStateEnum.SUPERVISOR):`
        ret_dict[ISAInstrClass.PPFSM] = 0
    
    # No exception if no exception is possible
    if (not fuzzerstate.authorize_privileges) or not fuzzerstate.privilegestate.is_ready_to_take_exception(fuzzerstate):
        ret_dict[ISAInstrClass.EXCEPTION] = 0
    
    if not fuzzerstate.privilegestate.privstate in (PrivilegeStateEnum.MACHINE, PrivilegeStateEnum.SUPERVISOR):
        ret_dict[ISAInstrClass.RANDOM_CSR] = 0
    
    if MAX_NUM_FENCES_PER_EXECUTION is not None and fuzzerstate.special_instrs_count > MAX_NUM_FENCES_PER_EXECUTION:
        pass
        # ret_dict[ISAInstrClass.SPECIAL] = 0

    # sfence.vma requires M or S mode, and supervisor mode support
    if not fuzzerstate.design_has_supervisor_mode \
        or not fuzzerstate.privilegestate.privstate in (PrivilegeStateEnum.MACHINE, PrivilegeStateEnum.SUPERVISOR):
        ret_dict[ISAInstrClass.SFENCE_VMA] = 0

    # Normalize the weights
    if DO_ASSERT:
        assert sum(ret_dict.values()) > 0, "The sum of filtered isa pick weights must be strictly positive!"
    norm_factor = 1/sum(ret_dict.values())
    for curr_key in ret_dict:
        ret_dict[curr_key] = ret_dict[curr_key] * norm_factor

    return ret_dict


# Sets the REGFSM weight to 0 if no register can be produced, consumed or relocated
def _filter_regfsm_weight(fuzzerstate: 'FuzzerState', filtered_weights: list):
    if fuzzerstate.intregpickstate.get_num_regs_in_state(IntRegIndivState.FREE) > NUM_MIN_FREE_INTREGS or \
        fuzzerstate.intregpickstate.exists_reg_in_state(IntRegIndivState.PRODUCED0) or \
        fuzzerstate.intregpickstate.exists_reg_in_state(IntRegIndivState.PRODUCED1):
        return
    
    filtered_weights[ISAInstrClass.REGFSM] = 0


# Filters out the sensitive instructions considering whether there are available registers in the suitable state
def _filter_sensitive_instr_weights(fuzzerstate: 'FuzzerState', filtered_weights: list):
    if not fuzzerstate.intregpickstate.exists_reg_in_state(IntRegIndivState.CONSUMED):
        filtered_weights[ISAInstrClass.JAL]     = 0
        filtered_weights[ISAInstrClass.MEDELEG] = 0
        # filtered_weights[ISAInstrClass.TVECFSM] = 0
        # filtered_weights[ISAInstrClass.EPCFSM]  = 0
        filtered_weights[ISAInstrClass.JALR]    = 0
        filtered_weights[ISAInstrClass.MEM]     = 0
        filtered_weights[ISAInstrClass.MEM64]   = 0
        filtered_weights[ISAInstrClass.MEMFPU]  = 0
        filtered_weights[ISAInstrClass.MEMFPUD] = 0
        filtered_weights[ISAInstrClass.AMO]     = 0
        filtered_weights[ISAInstrClass.AMO64]   = 0





